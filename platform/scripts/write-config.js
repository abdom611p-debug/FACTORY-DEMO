#!/usr/bin/env node
// Vercel build step: writes config.js from environment variables so the static UI knows where the backends live.
//   EGIC_API_BASE → EGIC platform server on Railway (REST + live stream), e.g. https://egic-platform.up.railway.app
//   EGIC_AI_URL   → EGIC AI Engine on Railway (Python), e.g. https://egic-ai.up.railway.app
'use strict';
const fs = require('fs');
const path = require('path');
const clean = (v) => String(v || '').trim().replace(/\/+$/, '');
const cfg = { apiBase: clean(process.env.EGIC_API_BASE), aiUrl: clean(process.env.EGIC_AI_URL) };
const out = '/*! generated by scripts/write-config.js at build time */\nwindow.EGIC_CONFIG = ' + JSON.stringify(cfg) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'config.js'), out);
console.log('config.js →', cfg);
